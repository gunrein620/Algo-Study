# 핸드폰 번호 가리기
# 내 반복문 풀이도 정답: reversed로 뒤에서 읽고 4개 보존, 다시 뒤집었다.
# range는 정수 위치를 주고, reversed(문자열)는 문자 자체를 준다.
# 슬라이싱으로 마지막 4글자를 바로 가져올 수 있다.


def solution(phone_number):
    return '*' * (len(phone_number) - 4) + phone_number[-4:]


# "321432"의 인덱스:  0  1  2  3  4  5
# 음수 인덱스:       -6 -5 -4 -3 -2 -1
# [-4:]는 뒤에서 네 번째부터 끝까지. 음수 위치가 역순을 뜻하진 않는다.
# [::-1]의 -1은 간격이므로 역순이다.
s = "321432"
print(s[-4])    # 1: 문자 하나
print(s[-4:])   # 1432: 마지막 4글자
print(s[:-4])   # 32: 마지막 4글자 앞까지
print(s[::-1])  # 234123: 전체 역순
print(solution(s))       # **1432
print(solution("1234"))  # 1234
