# 위에서부터 실행해도 되고, 한 구역씩 출력 결과를 먼저 예상해 봐도 된다.
# 핵심: 인덱스는 '위치', s[i]는 '그 위치의 값'이다.


# 1. 길이 / 위치 / 실제 값
s = "abcdef"
# 문자          a   b   c   d   e   f
# 양수 인덱스   0   1   2   3   4   5
# 음수 인덱스  -6  -5  -4  -3  -2  -1

i = 2
print(len(s))  # 6: 길이, int
print(i)       # 2: 위치, int
print(s[i])    # c: 실제 문자, str
print(s[4])    # e: 인덱싱은 s.[4]가 아니라 s[4]
print(s[-1])   # f: -1은 뒤에서 첫 번째 위치

# range로 만든 숫자를 순회하면 i에는 문자가 아니라 숫자가 들어간다.
for i in range(len(s) - 1, -1, -1):
    print(i, s[i])
# 출력:
# 5 f
# 4 e
# 3 d
# 2 c
# 1 b
# 0 a
# range(5, -1, -1): 5부터 1씩 줄이며, 끝값 -1은 제외한다.

# reversed(s)는 역순으로 문자를 꺼내는 이터레이터를 반환한다.
# 원본 s를 바꾸지 않는다. 빈 문자열이면 반복도 0번이다.
# '인덱스'가 필요 없고 '문자'만 필요할 때 바로 순회할 수 있다.
for char in reversed(s):
    print(char)
# 출력: f, e, d, c, b, a가 각각 한 줄씩 나온다.


# 2. 슬라이싱 기본 — 이건 코테에서 자주 쓰니 챙겨라.
# 문법: 대상[시작:끝:간격]
# 시작/끝은 위치를 나타내는 정수이고, 간격도 정수다. 생략할 수 있다.
# 시작은 포함, 끝은 제외한다. 간격을 생략하면 +1(오른쪽 한 칸)이다.
# 문자열을 자르면 str, 리스트를 자르면 list. 원본은 바뀌지 않는다.
print(s[1:4])  # bcd: 인덱스 1, 2, 3
print(s[2:5])  # cde: 마지막으로 포함할 위치가 4라서 끝에는 5
print(s)       # abcdef: 원본 유지


# 3. 시작 / 끝 생략 — 여기서는 간격이 +1이다.
print(s[:3])   # abc: 처음부터 인덱스 3 직전까지
print(s[2:])   # cdef: 인덱스 2부터 끝까지
print(s[:])    # abcdef: 전체


# 4. 음수 인덱스는 '위치'이지, 뒤집으라는 뜻이 아니다.
# 문자          a   b   c   d   e   f
# 음수 인덱스  -6  -5  -4  -3  -2  -1
print(s[-2:])  # ef: -2 위치의 e부터 오른쪽 끝까지
print(s[-4:])  # cdef: 마지막 4글자
print(s[-3:])  # def: 마지막 3글자
print(s[:-2])  # abcd: -2 위치의 e를 제외한 앞부분
print(s[:-4])  # ab: 마지막 4글자를 뺀 앞부분

# 원하는 결과 → 식
# 마지막 N글자: s[-N:] (N > 0일 때)
# 마지막 N글자 제외: s[:-N] (N > 0일 때)
# 주의: -0은 0이다. s[-0:]은 전체, s[:-0]은 빈 문자열이다.


# 5. 음수 step은 '방향'을 바꾼다.
print(s[-4:])   # cdef: 시작 위치만 음수, 간격은 기본 +1
print(s[::-1])  # fedcba: 간격 -1, 뒤에서 앞으로 한 칸씩
# 시작과 끝을 모두 생략하고 간격이 음수면 맨 뒤부터 맨 앞까지 간다.


# 6. 간격과 방향을 함께 적용
print(s[::2])     # ace: 인덱스 0 → 2 → 4
print(s[1::2])    # bdf: 인덱스 1 → 3 → 5
print(s[4:1:-1])  # edc: 인덱스 4 → 3 → 2, 끝 위치 1은 제외
print(s[5:2:-1])  # fed: 인덱스 5 → 4 → 3, 끝 위치 2는 제외
print(s[-3::-1])  # dcba: -3 위치의 d부터 왼쪽 끝까지
print(s[-2::-1])  # edcba: -2 위치의 e부터 왼쪽 끝까지

# 계산 순서: 시작 위치 찾기 → 간격만큼 이동 → 끝 위치 전에 멈추기
# 음수 step도 끝 제외 규칙은 같다.
# 주의: 끝을 생략하는 것과 끝에 -1을 쓰는 것은 다르다.
print(s[5:-1:-1])  # 빈 문자열: 시작 5와 끝 -1은 모두 f의 위치다.
print(s[5::-1])    # fedcba: 처음까지 가려면 끝을 생략한다.


# 7. 가운데 글자 — 먼저 idx가 '위치'라는 것을 기억하자.
def middle(s):
    # 이 문제의 입력 조건: 길이 1 이상인 문자열
    idx = len(s) // 2
    if len(s) % 2 == 1:
        return s[idx]
    else:
        return s[idx - 1:idx + 1]


print(middle("abcde"))   # c: 길이 5, idx = 2
print(middle("abcdef"))  # cd: 길이 6, idx = 3, s[2:4]
print(middle("a"))       # a: 길이 1, idx = 0, s[0]
print(middle("ab"))      # ab: 길이 2, idx = 1, s[0:2]

# 짝수 길이에서는 idx가 '가운데 두 위치 중 오른쪽'이다.
# abcdef의 가운데 위치는 2, 3이다. 3, 4가 아니다.
# 마지막 포함 위치가 idx이므로 슬라이싱 끝은 idx + 1이다.
# return은 함수 안에서 값을 돌려줄 때, print는 화면에 출력할 때 쓴다.


# 8. 슬라이싱 범위가 벗어날 때 / 빈 입력
short = "a"
print(short[-4:])   # a: 시작이 너무 앞이어도 가능한 범위만 가져온다.
print("ab"[-4:])    # ab
print(s[:100])      # abcdef: 끝이 너무 멀어도 오류 없이 끝까지
print(s[100:])      # 빈 문자열
print(s[3:1])       # 빈 문자열: 기본 방향 +1로는 3에서 1에 갈 수 없다.
print(""[:3])       # 빈 문자열
print([][:3])       # []
# 문자열이 비었는지 눈으로 확인하고 싶으면 길이도 함께 출력한다.
empty = s[3:1]
print(len(empty))   # 0
# 인덱싱 s[100]이나 ""[0]은 IndexError다. 슬라이싱과 구분하자.
# 간격 0인 s[::0]은 ValueError다. 0칸씩 이동할 수는 없다.


# 9. 문자열 / 리스트 반환 타입
a = "abcdef"
b = ["a", "b", "c", "d", "e", "f"]
print(a[1:3])        # bc
print(type(a[1:3]))  # <class 'str'>
print(b[1:3])        # ['b', 'c']
print(type(b[1:3]))  # <class 'list'>
print(b[1:2])        # ['b']: 하나만 남아도 슬라이싱은 리스트
print(b[1])          # b: 인덱싱은 원소 자체를 꺼낸다. 여기서는 str
# 리스트 슬라이싱은 새 리스트를 만든다(얕은 복사).
# 리스트 안에 또 리스트가 있다면 내부 리스트까지 복제하는 것은 아니다.


# 10. 함수 반환값에도 바로 슬라이싱할 수 있다.
n = 1204
result = str(n)[::-1]
print(result)        # 4021
print(type(result))  # <class 'str'>: 뒤집어도 문자열이다.

# 위 식을 중간 변수로 풀면 다음과 같다.
text = str(n)         # "1204", str
result = text[::-1]   # "4021", str
print(result)         # 4021

n = 123456
print(str(n)[-3:])    # 456: 정수가 아니라 문자열 "456"
print(str(1200)[::-1])  # 0021: 문자열이므로 앞의 0도 남는다.


# 11. 코테 적용: 전화번호 마지막 4글자만 남기기
# 입력 조건: phone은 길이 4 이상인 문자열
phone = "01012345678"
last = phone[-4:]
masked = "*" * (len(phone) - 4)
print(masked + last)  # *******5678

# 값과 타입 추적:
# len(phone)       → 11          int
# len(phone) - 4   → 7           int
# last            → "5678"      str
# masked          → "*******"   str
# masked + last   → "*******5678" str

phone = "1234"
last = phone[-4:]
masked = "*" * (len(phone) - 4)
print(masked + last)  # 1234: "*" * 0은 빈 문자열 ""

# 같은 패턴: 마지막 3글자만 남기고 앞을 #으로 바꾸기
s = "abcdefgh"
last = s[-3:]
masked = "#" * (len(s) - 3)
print(masked + last)  # #####fgh

# 실제로 틀렸던 문법과 수정 이유:
# last = [-3:]              → 자를 대상이 빠졌다. s[-3:]처럼 쓴다.
# "#" * len(s) - 3          → 문자열을 만든 뒤 3을 빼려 하므로 TypeError.
# "#" * (len(s) - 3)        → 개수를 먼저 계산하고 문자열을 반복한다.
# temp + last               → temp가 list, last가 str이면 연결할 수 없다.
# ''.join(temp) + last      → temp가 문자열 원소들의 리스트라면 이렇게 연결.
#                            하지만 여기서는 문자열 곱셈이 더 간단하다.
# 변수 이름도 확인: phone을 다룰 때 len(s)를 쓰면 다른 대상을 세게 된다.
# 여러 줄의 독립된 문장은 줄 끝에 역슬래시를 붙이지 않고 줄바꿈한다.


