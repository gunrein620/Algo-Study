# 최소직사각형
# 헷갈린 점: 명함을 돌리는 방법, max를 겹쳐 쓴 식의 의미.
# 내가 이해한 접근: 큰 수를 왼쪽으로 → 왼쪽 최대 × 오른쪽 최대.
# [60,50], [30,70], [60,30], [80,40]
#       → [60,50], [70,30], [60,30], [80,40]
# 왼쪽 최대 80, 오른쪽 최대 50 → 4000. 서로 다른 명함에서 나와도 된다.


def solution(sizes):
    width = 0
    height = 0

    for w, h in sizes:
        # 돌린다 = 긴 변을 가로, 짧은 변을 세로로 취급한다.
        # 원본 리스트를 실제로 바꿀 필요는 없다.
        long_side = max(w, h)
        short_side = min(w, h)

        # 기존 지갑보다 크면 늘리고, 작으면 기존 크기를 유지한다.
        width = max(width, long_side)
        height = max(height, short_side)

    return width * height


# 지갑 [60,50]에 명함 [70,30] 추가 → [max(60,70), max(50,30)] = [70,50]
# 가장 긴 변을 담을 한쪽은 반드시 필요하므로 그쪽에 긴 변들을 맞춘다.
# 반대쪽에는 짧은 변들이 오고, 그중 가장 큰 길이만큼 필요하다.
print(solution([[60, 50], [30, 70], [60, 30], [80, 40]]))  # 4000
print(solution([[10, 7], [12, 3], [8, 15], [14, 7], [5, 15]]))  # 120
print(solution([[14, 4], [19, 6], [6, 16], [18, 7], [7, 11]]))  # 133

# 직접 두 변수의 값을 바꿔도 된다. w, h = h, w는 값 교환.
w, h = 30, 70
if w < h:
    w, h = h, w
print(w, h)  # 70 30
